import {readFile, writeFile} from 'node:fs/promises';

// Preserve the existing cascade while serving one render-blocking stylesheet.
export async function buildStyles() {
  const source = new URL('../dist/', import.meta.url);
  const files = ['assets/fonts.css', 'style.css', 'readability.css', 'content-updates.css',
    'visual-refresh.css', 'booking-refresh.css', 'wheel-refresh.css', 'simplify.css'];
  const parts = [];
  for (const name of files) {
    let css = await readFile(new URL(name, source), 'utf8');
    if (name === 'assets/fonts.css') css = css.replace(/url\(\.\/([^)]*)\)/g, "url('/assets/$1')");
    parts.push(css.replace(/\/\*[\s\S]*?\*\//g, '').split(/\r?\n/).map(line => line.trim()).filter(Boolean).join('\n'));
  }
  await writeFile(new URL('site.css', source), '/* Generated by scripts/build-styles.mjs; edit the source stylesheets. */\n' + parts.join('\n') + '\n');
}
